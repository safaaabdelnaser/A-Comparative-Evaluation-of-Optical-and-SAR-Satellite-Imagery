import os
from PIL import Image
import matplotlib.pyplot as plt

folder_path = '/content/drive/MyDrive/Datasets/HRSC Dataset/runs/detect/predict'

image_files = [f for f in os.listdir(folder_path) if os.path.isfile(os.path.join(folder_path, f))]

num_images_per_row = 5
num_rows = 8
num_images_to_show = num_images_per_row * num_rows

# Calculate the figure size and individual subplot size for larger images
fig_width = 50
fig_height = 40
subplot_width = fig_width / num_images_per_row
subplot_height = fig_height / num_rows

# Create a figure and axis
fig, axs = plt.subplots(num_rows, num_images_per_row, figsize=(fig_width, fig_height))

for i, image_file in enumerate(image_files[:num_images_to_show]):
    # Create the image file path
    image_path = os.path.join(folder_path, image_file)

    # Open the image using PIL
    image = Image.open(image_path)

    # Calculate the row and column index for the subplot
    row_idx = i // num_images_per_row
    col_idx = i % num_images_per_row

    # Display the image using matplotlib
    axs[row_idx, col_idx].imshow(image)
    axs[row_idx, col_idx].axis('off')  # Turn off axes for cleaner display

# Hide any empty subplots
for i in range(num_images_to_show, num_rows*num_images_per_row):
    axs.flatten()[i].axis('off')

plt.show()